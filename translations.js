// Map of cached translations to prevent redundant API calls
const translationCache = {};

// Apply translations dynamically using Google Translate API
async function applyLanguage(lang) {
  // Update html lang attribute
  document.documentElement.lang = lang;

  // Update current language label in navbar
  const labels = { en:"EN", hi:"HI", kn:"KN", te:"TE", ta:"TA", mr:"MR", pa:"PA", bn:"BN" };
  const labelEl = document.getElementById("currentLangLabel");
  if (labelEl) labelEl.textContent = labels[lang] || "EN";

  // Mark active option
  document.querySelectorAll(".lang-option").forEach(opt => opt.classList.remove("active"));
  const activeOpt = document.querySelector(`.lang-option[onclick="setLanguage('${lang}')"]`);
  if (activeOpt) activeOpt.classList.add("active");

  // Save to localStorage
  localStorage.setItem("farmadvisor_lang", lang);
  closeLangMenu();
  updateFarmBotLanguage(lang);

  const elements = document.querySelectorAll("[data-lang]");

  if (lang === 'en') {
      elements.forEach(el => {
        const key = el.getAttribute("data-lang");
        if (translations.en[key]) {
          if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
            el.placeholder = translations.en[key];
          } else {
            el.textContent = translations.en[key];
          }
        }
      });
      return;
  }

  // Get all unique keys needed on this page
  const textsToTranslate = [];
  const keysToTranslate = [];
  
  elements.forEach(el => {
    const key = el.getAttribute("data-lang");
    if (translations.en[key] && !keysToTranslate.includes(key)) {
        // If already cached, apply immediately
        if (translationCache[lang] && translationCache[lang][key]) {
            // Already translated in cache, wait until later to apply it
        } else {
            keysToTranslate.push(key);
            textsToTranslate.push(translations.en[key]);
        }
    }
  });

  if (!translationCache[lang]) {
      translationCache[lang] = {};
  }

  // If there are new texts to translate via API
  if (textsToTranslate.length > 0) {
      // Use ~|~ as a delimiter that is unlikely to be translated or altered much
      const delimiter = ' ~|~ ';
      const combinedText = textsToTranslate.join(delimiter);
      
      try {
          const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=${lang}&dt=t&q=${encodeURIComponent(combinedText)}`;
          const response = await fetch(url);
          const data = await response.json();
          
          let translatedText = '';
          if (data && data[0]) {
              data[0].forEach(part => {
                  if (part[0]) translatedText += part[0];
              });
          }
          
          // Split back by delimiter (handle potential spacing variations added by translator)
          const translatedArray = translatedText.split(/~\s*\|\s*~/).map(s => s.trim());
          
          keysToTranslate.forEach((key, index) => {
              translationCache[lang][key] = translatedArray[index] || translations.en[key];
          });
      } catch (error) {
          console.error("Translation API Error:", error);
      }
  }

  // Apply to DOM
  elements.forEach(el => {
    const key = el.getAttribute("data-lang");
    const translatedText = (translationCache[lang] && translationCache[lang][key]) || translations.en[key];
    
    if (translatedText) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = translatedText;
      } else {
        el.textContent = translatedText;
      }
    }
  });
}

function setLanguage(lang) {
  applyLanguage(lang);
}

function toggleLangMenu() {
  document.getElementById("langDropdown").classList.toggle("open");
}

function closeLangMenu() {
  const dropdown = document.getElementById("langDropdown");
  if (dropdown) dropdown.classList.remove("open");
}

// Close dropdown when clicking outside
document.addEventListener("click", function(e) {
  const switcher = document.getElementById("langSwitcher");
  if (switcher && !switcher.contains(e.target)) closeLangMenu();
});

// Update FarmBot language instruction
function updateFarmBotLanguage(lang) {
  const langNames = {
    en: "English", hi: "Hindi", kn: "Kannada", te: "Telugu",
    ta: "Tamil", mr: "Marathi", pa: "Punjabi", bn: "Bengali"
  };
  window.FARMBOT_REPLY_LANGUAGE = langNames[lang] || "English";
}

// Load saved language on every page
window.addEventListener("DOMContentLoaded", function() {
  const saved = localStorage.getItem("farmadvisor_lang") || "en";
  applyLanguage(saved);
});
